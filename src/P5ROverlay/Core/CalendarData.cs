    /// <summary>某一天的日程：白天一段、夜晚一段，各自内部用 \n 分隔条目。</summary>
    public sealed class DayPlan
    {
        public readonly string Day;
        public readonly string Night;

        public DayPlan(string day, string night) { Day = day ?? ""; Night = night ?? ""; }

        public bool Empty => Day.Length == 0 && Night.Length == 0;

        public string[] DayItems => Split(Day);
        public string[] NightItems => Split(Night);

        private static readonly string[] None = new string[0];
        private static string[] Split(string s)
        {
            if (string.IsNullOrEmpty(s)) return None;
            return s.Split('\n');
        }
    }

