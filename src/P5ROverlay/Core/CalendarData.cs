        /// <summary>取某人某天的日程；超出表格范围返回 null。</summary>
        public static DayPlan Get(int month, int day)
        {
            if (Days.TryGetValue(month * 100 + day, out var p)) return p;
            return null;
        }

        public static DayPlan Get(DateTime d) => Get(d.Month, d.Day);

        /// <summary>这一天是否有安排可看（用于日历格子上的小红点）。</summary>
        public static bool Has(int month, int day)
        {
            var p = Get(month, day);
            return p != null && !p.Empty;
        }
